import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { REPO_ROOT } from "./moduleRunner.ts";

/**
 * The send-time label-fit measure (src/core/pi/cardFigureFit.ts) cannot lay
 * out text, so it reads each printable ASCII character's advance, in ems, from
 * the card font as Chromium draws it. Run it again only when the card font
 * changes; the table is not checked against a browser on every `pnpm check`.
 */
const FONT = join(REPO_ROOT, "src/renderer/src/design/assets/fonts/spacegrotesk-latin.woff2");
const OUT = join(REPO_ROOT, "src/core/pi/cardGlyphWidths.generated.ts");
const WEIGHTS = [400, 600] as const;

const chars = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i));
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const font = readFileSync(FONT).toString("base64");
  await page.setContent(
    `<style>@font-face{font-family:SG;font-weight:300 700;src:url(data:font/woff2;base64,${font}) format("woff2")}</style>
<svg xmlns="http://www.w3.org/2000/svg" width="4000" height="100"><text id="t" y="50" font-family="SG" font-size="1000" xml:space="preserve"></text></svg>`,
  );
  await page.evaluate(() => document.fonts.load("400 1000px SG"));
  await page.evaluate(() => document.fonts.load("600 1000px SG"));
  const widths: Record<number, number[]> = {};
  for (const weight of WEIGHTS) {
    widths[weight] = await page.evaluate(
      ([list, w]) => {
        const text = document.getElementById("t") as unknown as SVGTextContentElement;
        text.setAttribute("font-weight", String(w));
        return (list as string[]).map((c) => {
          text.textContent = c;
          return Math.round((text.getComputedTextLength() / 1000) * 10000) / 10000;
        });
      },
      [chars, weight] as const,
    );
  }
  const row = (weight: number) => `  ${weight}: [${widths[weight]!.join(", ")}],`;
  writeFileSync(
    OUT,
    `// Generated by scripts/generate-card-glyph-widths.ts; do not edit by hand.
/** Advance of U+0020 to U+007E in the card font, in ems, by font weight. */
export const GLYPH_ADVANCES: Record<number, readonly number[]> = {
${WEIGHTS.map(row).join("\n")}
};
`,
  );
} finally {
  await browser.close();
}
