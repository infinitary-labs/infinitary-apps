import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

/**
 * Renders the personal workspace's `infinitary-env.d.ts` from the type-only
 * contracts in src/shared/personal/contracts.ts (talk-to-personalize Step
 * 2), and writes it as a TS module the
 * seeder imports (src/core/personal/seed/infinitaryEnv.generated.ts). The
 * freshness test (src/core/personal/infinitaryEnv.test.ts) renders again
 * and compares, so a contracts change without `pnpm generate:personal-env`
 * fails CI.
 *
 * What is rendered: every exported type alias and interface of contracts.ts,
 * with its JSDoc, inside `declare module "@infinitary/contracts"`, each
 * sibling file it re-exports whole (`export type * from "./x"`) rendered the
 * same way where that line stands, and the one other
 * module a panel imports from its own folder: a stylesheet, which the
 * compiler admits as text (docs/ui-plugins.md, "A panel's cards"). The
 * contracts import nothing, so the file stands alone in a workspace with
 * no node_modules.
 */
const PREAMBLE = `// Generated by scripts/generate-personal-env.ts from src/shared/personal/contracts.ts.
// Managed by Infinitary: restored at every launch. Do not edit.
//
// The types a personal extension may name. Import them type-only:
//   import type { PanelProps } from "@infinitary/contracts";
`;

export function renderInfinitaryEnv(
  contractsSource: string,
  readSibling: (specifier: string) => string = (specifier) =>
    readFileSync(join(dirname(CONTRACTS_PATH), `${specifier}.ts`), "utf8"),
): string {
  const blocks = contractBlocks("contracts.ts", contractsSource, readSibling);
  if (blocks.length === 0) throw new Error("contracts.ts exports no type alias or interface");
  return (
    `${PREAMBLE}\ndeclare module "@infinitary/contracts" {\n${blocks.join("\n\n")}\n}\n` +
    OLDER_CONTRACTS_MODULE +
    STYLESHEET_MODULE
  );
}

/**
 * The same types under Firstmate 3000's name for them (src/shared/codeNames.ts),
 * which the compiler admits as the same module, so a panel written before
 * the rename type-checks here too.
 */
const OLDER_CONTRACTS_MODULE = `
declare module "@firstmate/contracts" {
  export * from "@infinitary/contracts";
}
`;

/** A panel's own stylesheet, as the compiler admits it: its text, by one default import. */
const STYLESHEET_MODULE = `
declare module "*.css" {
  /** The stylesheet's text: put it in a \`<style>\` of the panel's own. */
  const text: string;
  export default text;
}
`;

function contractBlocks(
  name: string,
  source: string,
  readSibling: (specifier: string) => string,
): string[] {
  const file = ts.createSourceFile(name, source, ts.ScriptTarget.Latest, true);
  return file.statements.flatMap((statement): string[] => {
    if (
      ts.isExportDeclaration(statement) &&
      statement.isTypeOnly &&
      !statement.exportClause &&
      statement.moduleSpecifier &&
      ts.isStringLiteral(statement.moduleSpecifier)
    ) {
      const specifier = statement.moduleSpecifier.text;
      return contractBlocks(specifier, readSibling(specifier), readSibling);
    }
    if (!ts.isTypeAliasDeclaration(statement) && !ts.isInterfaceDeclaration(statement)) return [];
    const exported = statement.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
    );
    return exported ? [indent(statement.getFullText(file).trim())] : [];
  });
}

function indent(block: string): string {
  return block
    .split("\n")
    .map((line) => (line.length > 0 ? `  ${line}` : line))
    .join("\n");
}

export function renderGeneratedModule(dts: string): string {
  // A template literal: biome leaves those alone, so `pnpm check` and the
  // freshness test agree on the same bytes.
  const escaped = dts.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return (
    "// Generated by scripts/generate-personal-env.ts. Do not edit; run `pnpm generate:personal-env`.\n" +
    `export const INFINITARY_ENV_DTS = \`${escaped}\`;\n`
  );
}

const here = dirname(fileURLToPath(import.meta.url));
export const CONTRACTS_PATH = join(here, "..", "src", "shared", "personal", "contracts.ts");
export const GENERATED_PATH = join(
  here,
  "..",
  "src",
  "core",
  "personal",
  "seed",
  "infinitaryEnv.generated.ts",
);

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dts = renderInfinitaryEnv(readFileSync(CONTRACTS_PATH, "utf8"));
  writeFileSync(GENERATED_PATH, renderGeneratedModule(dts));
  console.log(`Wrote ${GENERATED_PATH}`);
}
