import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { staleGeneratedFile } from "./github-errors.ts";

// These defaults also serve plain-Node consumers, which cannot import Markdown.
const sections = {
  deliveryGuide: "delivery/crew.md",
  namingGuide: "naming/guide.md",
  testingGuide: "testing/crew.md",
};
const output = fileURLToPath(new URL("../src/core/runbooks/fallback.generated.ts", import.meta.url));
const text = `// Generated by scripts/generate-runbook-fallback.ts; edit the Markdown sections instead.\n${Object.entries(sections).map(([name, file]) => {
  const section = readFileSync(new URL(`../resources/runbooks/${file}`, import.meta.url), "utf8").trim();
  return `export const ${name} =\n  ${JSON.stringify(section)};`;
}).join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) throw staleGeneratedFile("src/core/runbooks/fallback.generated.ts", "node scripts/generate-runbook-fallback.ts");
} else writeFileSync(output, text);
