/** The stamp's words after its comment mark, on each shipped file's first line (the second under a shebang). */
const STAMP_WORDS = (version: number) =>
  `Infinitary queue ${version}. Generated by Infinitary from one source; a newer Infinitary offers its update as a pull request, so change it there, not by hand.`;
const STAMP = /^(?:#|\/\/) Infinitary queue (\d+)\. Generated by Infinitary/m;

/** The shipped queue's version a file's stamp names, or undefined when it carries none. */
export function readQueueStamp(text: string): number | undefined {
  const found = STAMP.exec(text);
  return found ? Number(found[1]) : undefined;
}

/**
 * A host part: where the queue's files go in a project on that host, the
 * one file that names the queue (its stamp is what every teammate's
 * Infinitary reads), and the file the project writes itself to name its
 * batch's checks.
 */
export type QueueHostPart = {
  /** The host's name as a heading names it. */
  name: string;
  /** The folder of the queue-setup skill its files are written to. */
  folder: string;
  /** The sources whose hash is this part's version, in the order they are hashed. */
  hashed: readonly ShippedSource[];
  /** This part's version history (see `GITHUB_QUEUE_SOURCES`). */
  sources: readonly string[];
  /** This part's version: how many sources it has had. */
  version: number;
  /** Each shipped file, from its source in `./shipped/` to its path in the project. */
  files: readonly { source: ShippedSource; path: string }[];
  /** The file whose stamp says the project runs the shipped queue. */
  queueFile: string;
  /** The project's own file that runs the batch's checks on the composed batch. */
  checksFile: string;
};

