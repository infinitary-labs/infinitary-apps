import { clamp01, easeInOut, TAU } from "./face";

// The cinch: how the first mate shows that it is shortening its conversation
// (captain's pick, option C of INF-3011's preview). A ring is thrown round
// the body and drawn tight, pulling it smaller; loose motes stream in from
// outside to the centre, which brightens as they arrive; while it holds, a
// glint runs round the ring on the rhythm and a few motes keep trickling
// in; at the end the ring loosens and fades, the body springs back past its
// size with a lift of light, and the eyes take one slow blink.
//
// Folding is a PARAMETER over the working state, like busy and the crystal -
// never a state (the machine carries it and never acts on it), so the
// canvas's aria-label stays the state name. firstmatePainter.ts owns the gate
// (attention and emotes ease the cinch out; it comes back if the shortening
// is still running), the projection and the halo; this module owns the
// envelope, the motes and the ring, and hands the host the restyle it needs.
// The phone draws the same look from these numbers (CharacterCinch.swift,
// its settings generated by scripts/generate-phone-scene.ts).
//
// Everything is DOM-free apart from the CanvasRenderingContext2D it paints.

/** The captain's settings from the preview, and the look's own constants. */
export const CINCH = {
  /** The body's size at full tightness, as a share of its own. */
  tightness: 0.45,
  /** The ring's throw and the draw tight, ms. */
  inMs: 900,
  /** The loosening and spring back, ms. */
  outMs: 1100,
  /** One loosen-and-tighten while it holds, s. */
  rhythmS: 2.4,
  /** The lift of light at the end. */
  release: 0.7,
  /** How far the hold loosens on each rhythm. */
  pump: 0.1,
  /** Share of the turn the body keeps while drawn tight. */
  spinKeep: 0.55,
  /** How far the eyes narrow. */
  lid: 0.45,
  /** How much the outer cell's wires dim. */
  outerDim: 0.35,
  /** The ring's radius thrown and drawn tight, in units of the body's resting radius. */
  ringFrom: 1.5,
  ringTight: 0.95,
  /** How far the ring loosens outward as it fades. */
  ringGrow: 0.7,
  /** Share of the start the throw round the body takes. */
  throwShare: 0.45,
  /** One mote every this many ms while the ring is drawn tight, and while it holds. */
  moteInMs: 110,
  moteHoldMs: 625,
  /** A mote's flight to the centre, ms, and its spread. */
  moteLifeMs: 750,
  moteLifeSpread: 300,
  /** How long the centre stays bright after a mote arrives, ms. */
  arrivalMs: 400,
} as const;

/** One frame of a cinch: its phase, the tightness `k` (it overshoots below 0 on the way out) and its light. */
export type CinchFrame = {
  phase: "in" | "hold" | "out";
  /** 0 at rest .. 1 drawn tight; dips below 0 as the body springs back past its size. */
  k: number;
  /** Ms since the cinch began. */
  t: number;
  /** Seconds into the hold (the glint's and the pump's clock). */
  holdS: number;
  /** Progress through the end, 0..1. */
  u: number;
  /** How visible the ring and motes are. */
  vis: number;
  /** The lift of light at the end. */
  lift: number;
  /** When the hold ends (ms since the start), or Infinity while the shortening runs. */
  holdEnd: number;
};

const back = (t: number): number => {
  const c1 = 1.70158;
  return 1 + (c1 + 1) * (t - 1) ** 3 + c1 * (t - 1) ** 2;
};

/** The hold's loosen-and-tighten, 0..1, at `holdS` seconds into it. */
function pumpAt(holdS: number): number {
  return 0.5 - 0.5 * Math.cos((TAU * holdS) / CINCH.rhythmS);
}

/**
 * The cinch at `t` ms since it began. `endedAt` is when the shortening ended
 * (ms since the start), or null while it runs. A shortening shorter than the
 * start - or one only heard ending - plays the start whole, then the end:
 * the short version. Null once the end has played.
 */
export function cinchFrame(t: number, endedAt: number | null): CinchFrame | null {
  if (t < 0) return null;
  const holdEnd = endedAt === null ? Number.POSITIVE_INFINITY : Math.max(endedAt, CINCH.inMs);
  if (t < CINCH.inMs) {
    const k = easeInOut(t / CINCH.inMs);
    return {
      phase: "in",
      k,
      t,
      holdS: 0,
      u: 0,
      vis: clamp01(t / (CINCH.inMs * 0.3)),
      lift: 0,
      holdEnd,
    };
  }
  if (t < holdEnd) {
    const holdS = (t - CINCH.inMs) / 1000;
    return {
      phase: "hold",
      k: 1 - CINCH.pump * pumpAt(holdS),
      t,
      holdS,
      u: 0,
      vis: 1,
      lift: 0,
      holdEnd,
    };
  }
  const u = (t - holdEnd) / CINCH.outMs;
  if (u >= 1) return null;
  const holdS = (holdEnd - CINCH.inMs) / 1000;
  const k0 = 1 - CINCH.pump * pumpAt(holdS);
  return {
    phase: "out",
    k: k0 * (1 - back(u)),
    t,
    holdS,
    u,
    vis: 1 - easeInOut(u),
    lift: Math.sin(Math.PI * u) * CINCH.release,
    holdEnd,
  };
}

/** Reduce Motion's still: the tight pose while the shortening runs, with no start, end or rhythm. */
export function cinchStill(folding: boolean): CinchFrame | null {
  if (!folding) return null;
  return {
    phase: "hold",
    k: 1,
    t: CINCH.inMs,
    holdS: 0,
    u: 0,
    vis: 1,
    lift: 0,
    holdEnd: Number.POSITIVE_INFINITY,
  };
}

/**
 * When the current cinch began and whether its shortening has ended. Each
 * new start (`starts` rising) begins one, even one whose end was heard in
 * the same breath, so a shortening only heard ending still plays.
 */
export class CinchClock {
  private seen: number;
  private at = Number.NEGATIVE_INFINITY;
  private endedAt: number | null = 0;

  constructor(starts: number) {
    this.seen = starts;
  }

  /** Read the inputs at `now`: the folding fact and the count of starts heard. */
  update(now: number, folding: boolean, starts: number): void {
    const running = this.endedAt === null;
    if (starts !== this.seen || (folding && !running)) {
      this.seen = starts;
      this.at = now;
      this.endedAt = null;
    }
    if (!folding && this.endedAt === null) this.endedAt = now - this.at;
  }

  frame(now: number): CinchFrame | null {
    return cinchFrame(now - this.at, this.endedAt);
  }
}

/** A deterministic 0..1 for a mote's slot. */
export function moteHash(slot: number): number {
  const x = Math.sin(slot * 12.9898 + 78.233) * 43758.5453;
  return x - Math.floor(x);
}

/** A mote in flight: which slot it is (it picks the vertex and reach) and how far it has come, 0..1. */
export type Mote = { slot: number; u: number };

function lifeOf(slot: number): number {
  return CINCH.moteLifeMs + CINCH.moteLifeSpread * moteHash(slot + 0.5);
}

/**
 * The motes in flight at a frame, and how bright the centre is from the
 * ones that just arrived (0..1). Motes are born quickly while the ring is
 * drawn tight and slowly while it holds, never after; each flies its own life.
 */
export function cinchMotes(frame: CinchFrame): { motes: Mote[]; arrival: number } {
  const motes: Mote[] = [];
  let arrival = 0;
  const birthsEnd = Math.min(frame.t, frame.holdEnd);
  const visit = (slot: number, born: number) => {
    const age = frame.t - born;
    const life = lifeOf(slot);
    if (age < 0) return;
    if (age < life) motes.push({ slot, u: age / life });
    else arrival = Math.max(arrival, Math.exp(-(age - life) / CINCH.arrivalMs));
  };
  const reach = CINCH.moteLifeMs + CINCH.moteLifeSpread + CINCH.arrivalMs * 3;
  const inCount = Math.ceil(CINCH.inMs / CINCH.moteInMs);
  for (let j = 0; j < inCount; j++) {
    const born = j * CINCH.moteInMs;
    if (born > birthsEnd) break;
    if (frame.t - born < reach) visit(j, born);
  }
  if (birthsEnd > CINCH.inMs) {
    const first = Math.max(0, Math.floor((frame.t - reach - CINCH.inMs) / CINCH.moteHoldMs));
    for (let j = first; ; j++) {
      const born = CINCH.inMs + j * CINCH.moteHoldMs;
      if (born > birthsEnd) break;
      visit(1000 + j, born);
    }
  }
  return { motes, arrival };
}

/** What the cinch asks of the body at tightness `k`. */
export function cinchBody(k: number): {
  /** The body's radius, as a share of its own (above 1 as it springs back). */
  scale: number;
  /** The share of the turn it keeps. */
  spin: number;
  lid: number;
  /** The outer cell's wire strength. */
  outer: number;
  /** The working look, moved down toward the centre. */
  look: [number, number];
} {
  const kz = clamp01(k);
  return {
    scale: 1 - (1 - CINCH.tightness) * k,
    spin: 1 - (1 - CINCH.spinKeep) * kz,
    lid: CINCH.lid * kz,
    outer: 1 - CINCH.outerDim * kz,
    look: [0.12 * (1 - kz), 0.4 - 0.3 * kz],
  };
}

export type Rgb = [number, number, number];

/** Projected vertex: screen x, screen y, depth scale, 4D w. */
export type CinchPt = [number, number, number, number];

export type CinchEnv = {
  ctx: CanvasRenderingContext2D;
  frame: CinchFrame;
  /** The tightness as drawn: the frame's, gated by the working state. */
  k: number;
  /** The working state's gate, 0..1: attention and emotes ease the cinch out. */
  gate: number;
  c: number;
  /** The body's resting radius, before the cinch scales it. */
  R0: number;
  size: number;
  pts: CinchPt[];
  /** Reduce Motion: no glint, no motes. */
  still: boolean;
  colors: { dim: Rgb; bright: Rgb; boost: number };
};

const WARM: Rgb = [255, 246, 230];

/** The centre's fill and the ring, with its glint while it holds: under the wires. */
export function drawCinchUnder(env: CinchEnv, arrival: number): void {
  const { ctx, frame, c, R0, colors } = env;
  const kz = clamp01(env.k);
  const gate = env.gate;
  const vis = frame.vis * gate;
  if (vis <= 0.01 && kz <= 0.01) return;
  const R = R0 * cinchBody(env.k).scale;
  ctx.save();
  if (kz > 0.01) {
    const fill = env.still ? 0.6 : 0.35 + 0.65 * arrival;
    const cy = c - 0.04 * R;
    const g = ctx.createRadialGradient(c, cy, 0, c, cy, R * 0.5);
    g.addColorStop(0, rgbaOf(mixRgb(colors.bright, WARM, 0.3), 0.26 * kz * fill));
    g.addColorStop(1, rgbaOf(colors.bright, 0));
    ctx.fillStyle = g;
    ctx.beginPath();
    ctx.arc(c, cy, R * 0.5, 0, TAU);
    ctx.fill();
  }
  const grow = frame.phase === "out" ? easeInOut(frame.u) * R0 * CINCH.ringGrow : 0;
  const rr = R0 * (CINCH.ringFrom * (1 - kz) + CINCH.ringTight * CINCH.tightness * kz) + grow;
  const sweep =
    frame.phase === "in" ? clamp01(frame.t / (CINCH.inMs * CINCH.throwShare)) * TAU : TAU;
  const s = env.size / 280;
  ctx.lineCap = "round";
  ctx.strokeStyle = rgbaOf(
    mixRgb(colors.dim, colors.bright, 0.6),
    Math.min(1, 0.5 * vis * colors.boost),
  );
  ctx.lineWidth = 1.3 * s;
  ctx.beginPath();
  ctx.arc(c, c, rr, -Math.PI / 2, -Math.PI / 2 + sweep);
  ctx.stroke();
  if (frame.phase === "hold" && !env.still) {
    const th = -Math.PI / 2 + (TAU * frame.holdS) / CINCH.rhythmS;
    const glint = mixRgb(colors.bright, WARM, 0.5);
    ctx.strokeStyle = rgbaOf(glint, Math.min(1, 0.12 * colors.boost * gate));
    ctx.lineWidth = 6 * s;
    ctx.beginPath();
    ctx.arc(c, c, rr, th - 0.35, th + 0.35);
    ctx.stroke();
    ctx.strokeStyle = rgbaOf(glint, Math.min(1, 0.95 * colors.boost * gate));
    ctx.lineWidth = 2 * s;
    ctx.beginPath();
    ctx.arc(c, c, rr, th - 0.3, th + 0.3);
    ctx.stroke();
  }
  ctx.restore();
}

/** The motes streaming in to the centre: over the wires, under the eyes. */
export function drawCinchOver(env: CinchEnv, motes: readonly Mote[]): void {
  if (env.still || motes.length === 0) return;
  const { ctx, c, pts, colors } = env;
  const gate = env.gate;
  const R = env.R0 * cinchBody(env.k).scale;
  const tx = c;
  const ty = c - 0.04 * R;
  const col = mixRgb(colors.bright, WARM, 0.3);
  const s = env.size / 280;
  ctx.save();
  ctx.lineCap = "round";
  ctx.lineWidth = 1 * s;
  for (const m of motes) {
    // Each mote leaves from beyond one of the outer cell's corners.
    const P = sourceOf(pts, m.slot);
    const dx = P[0] - c;
    const dy = P[1] - c;
    const d = Math.hypot(dx, dy) || 1;
    const out = (d + env.R0 * 0.35) * (1 + 0.4 * moteHash(m.slot + 0.25));
    const x0 = c + (dx / d) * out;
    const y0 = c + (dy / d) * out;
    const u = m.u ** 1.6;
    const u2 = Math.max(0, m.u - 0.1) ** 1.6;
    const fade = gate * env.frame.vis * (1 - u * 0.6);
    const x = x0 + (tx - x0) * u;
    const y = y0 + (ty - y0) * u;
    ctx.strokeStyle = rgbaOf(col, 0.45 * fade);
    ctx.beginPath();
    ctx.moveTo(x0 + (tx - x0) * u2, y0 + (ty - y0) * u2);
    ctx.lineTo(x, y);
    ctx.stroke();
    ctx.fillStyle = rgbaOf(col, 0.9 * fade);
    ctx.beginPath();
    ctx.arc(x, y, 1.8 * s * (1 - 0.5 * u), 0, TAU);
    ctx.fill();
  }
  ctx.restore();
}

/** A mote's corner: one of the outer cell's vertices (4D w above 0), picked by its slot. */
function sourceOf(pts: readonly CinchPt[], slot: number): CinchPt {
  const outer = pts.filter((p) => p[3] > 0);
  const from = outer.length > 0 ? outer : pts;
  return from[Math.floor(moteHash(slot) * from.length) % from.length] as CinchPt;
}

function mixRgb(a: Rgb, b: Rgb, t: number): Rgb {
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
}

function rgbaOf(col: Rgb, alpha: number): string {
  return `rgba(${Math.round(col[0])},${Math.round(col[1])},${Math.round(col[2])},${Math.max(0, alpha)})`;
}
