import sources from "./appParts.generated.json" with { type: "json" };

/**
 * The app's own card parts (docs/card-authoring.md, "Parts by reference"):
 * code a runbook's part needs on every card that draws it, such as the
 * architecture map's, which the app ships rather than each card carrying a
 * copy. A body names one with an empty `<script data-inf-part="map"></script>`,
 * and every reader - the window, a view of another computer and the phone -
 * puts this build's own style and script in its place before the body's
 * scripts are hashed, so the part's code never counts toward the card's
 * size. A body can only name a part; it never supplies one.
 *
 * Generated by `scripts/generate-runbook-parts.ts` from the readable sources
 * in `src/core/runbooks/parts/`.
 */
const APP_PART_SOURCES: Readonly<Record<string, { style: string; script: string }>> = sources;

/** The names a body may give `data-inf-part`. */
export const APP_PART_NAMES: readonly string[] = Object.keys(APP_PART_SOURCES);

/** The one form a reference takes: an empty script naming the part, nothing else on it. */
const REFERENCE = /<script data-inf-part="([a-z][a-z0-9-]*)"><\/script>/g;
/** The same form, read only where a naming tag starts. */
const REFERENCE_AT = new RegExp(REFERENCE.source, "y");
/** Any script tag that carries the attribute, written in the one form or not. */
const NAMING = /<script\b[^>]*\bdata-inf-part\b[^>]*>/gi;

/**
 * What is wrong with a body's part references, for the card checks to refuse:
 * a reference written in another form, which no reader would fill, or one
 * naming a part this build does not ship. Undefined when every one is sound.
 */
export function appPartProblem(body: string): string | undefined {
  for (const match of body.matchAll(NAMING)) {
    const at = match.index ?? 0;
    REFERENCE_AT.lastIndex = at;
    const reference = REFERENCE_AT.exec(body);
    if (!reference) {
      return `${match[0]} is not a part reference the app fills: write it exactly as <script data-inf-part="<name>"></script>, empty and with nothing else on it.`;
    }
    const name = reference[1] ?? "";
    if (!Object.hasOwn(APP_PART_SOURCES, name)) {
      return `<script data-inf-part="${name}"> names no part the app ships; its parts are ${APP_PART_NAMES.join(", ")}.`;
    }
  }
  return undefined;
}

/**
 * The markup with each reference to a part this build ships replaced by the
 * part's style and script, in place. A reference to any other name is left
 * as written: an empty script, which runs nothing.
 */
export function withAppParts(html: string): string {
  if (!html.includes("data-inf-part")) return html;
  return html.replace(REFERENCE, (reference, name: string) => {
    const part = Object.hasOwn(APP_PART_SOURCES, name) ? APP_PART_SOURCES[name] : undefined;
    return part ? `<style>${part.style}</style><script>${part.script}</script>` : reference;
  });
}
